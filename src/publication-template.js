export function adDescription(car,p=car.publication||{}){
 const description=String(p.description||'').trim();
 if(p.useStandardText===false)return description;
 const values={'марка':car.brand||'','модель':car.model||'','год':car.year||'','год_выпуска':car.year?car.year+' года выпуска':''};
 const text=String(p.standardText??DEFAULT_AD_TEXT).replace(/\{(марка|модель|год|год_выпуска)\}/g,(_,key)=>String(values[key])).replace(/[ \t]+\./g,'.').trim();
 return [description,text].filter(Boolean).join('\n\n');
}
